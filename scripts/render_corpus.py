#!/usr/bin/env python3
"""Write docs/CORPUS.md from the conformance corpus in tests/corpus (#80).

Usage: ``python scripts/render_corpus.py`` (``--check`` only compares).
tests/test_corpus.py fails when the document and the corpus disagree.
"""

import json
import sys
from collections import OrderedDict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "tests"))

import _corpus  # noqa: E402

OUTPUT = ROOT / "docs" / "CORPUS.md"
REPO = "https://github.com/sahebbiswas/cddl_verifier"

STATUS_TEXT = OrderedDict([
    ("pass", "this library gives the verdict of the source"),
    ("gap", "the library is wrong or does not do it yet: there is an issue, and the case keeps failing until it is fixed"),
    ("divergence", "the library differs on purpose, for the reason given"),
    ("source-defect", "the source's own schema or example is wrong, for the reason given; the library is right"),
])
PROVENANCE_TEXT = OrderedDict([
    ("verbatim", "schema text and data bytes exactly as published"),
    ("converted", "published in diagnostic notation (EDN) and converted to CBOR with `cbor-diag`"),
    ("derived", "a published example changed in one stated way (a field removed, a tag changed, ...)"),
    ("adapted", "published text with rules added to make it usable (an adapter that wraps a sequence in an array, a stand-in for a module that is not bundled)"),
    ("constructed", "written for this corpus from the rules of the schema or section named"),
])


def cell(text) -> str:
    return str(text).replace("|", "\\|").replace("\n", " ")


def issue_link(number) -> str:
    return f"[#{number}]({REPO}/issues/{number})" if number else ""


def plural(count, word):
    return f"{count} {word}" + ("" if count == 1 else "s")


def render(suites, matrix_rows) -> str:
    out = []
    add = out.append
    add("# Conformance corpus")
    add("")
    add("<!-- Generated by scripts/render_corpus.py from tests/corpus: do not edit. -->")
    add("")
    total = sum(len(suite["cases"]) for suite in suites)
    add("Schemas and CBOR from the RFCs and IETF drafts that use CDDL (RFC 8610 and RFC 9165 constructs, "
        "COSE, CoRIM, CoSWID, EDHOC, SUIT), each with the verdict its source gives, the constructs "
        "it exercises and where it came from. `tests/test_corpus.py` runs every case, so this page cannot "
        "describe behaviour the library does not have. The construct-by-construct view is the "
        "[conformance matrix](CONFORMANCE.md); this is the same question asked with real schemas.")
    add("")
    add(f"{plural(total, 'case')} in {plural(len(suites), 'suite')}. Cases that the library disagrees with "
        "are not hidden: each one carries a status and a reason, and keeps failing the test until the "
        "disagreement goes away (see *Statuses*).")
    add("")
    add("## Suites")
    add("")
    add("| Suite | What it covers | Cases | Pass | Gap | Divergence | Source defect |")
    add("|---|---|--:|--:|--:|--:|--:|")
    for suite in suites:
        counts = {key: 0 for key in STATUS_TEXT}
        for entry in suite["cases"]:
            counts[_corpus.status_of(entry)] += 1
        add(f"| `{suite['id']}` | {cell(suite['title'])} | {len(suite['cases'])} | {counts['pass']} | "
            f"{counts['gap'] or ''} | {counts['divergence'] or ''} | {counts['source-defect'] or ''} |")
    add("")
    add("## Statuses")
    add("")
    add("| Status | Meaning |")
    add("|---|---|")
    for key, text in STATUS_TEXT.items():
        add(f"| `{key}` | {text} |")
    add("")
    add("## Provenance")
    add("")
    add("| Provenance | Meaning |")
    add("|---|---|")
    for key, text in PROVENANCE_TEXT.items():
        add(f"| `{key}` | {text} |")
    add("")
    add("## Sources")
    add("")
    add("Every source is pinned to the commit it was taken from. Text published in IETF documents is "
        "under the IETF Trust Legal Provisions; the licence of each repository is named below.")
    add("")
    add("| Suite | Source | Commit | Licence |")
    add("|---|---|---|---|")
    for suite in suites:
        for source in suite["sources"]:
            where = f"[{cell(source['name'])}]({source['url']})" + (f" (`{source['path']}`)" if source.get("path") else "")
            commit = f"`{source['commit'][:12]}` ({source['date']})" if source.get("commit") else cell(source.get("note", ""))
            add(f"| `{suite['id']}` | {where} | {commit} | {cell(source['license'])} |")
    add("")
    add("## Known gaps, divergences and source defects")
    add("")
    groups = OrderedDict()
    for suite, entry in _corpus.iter_cases(suites):
        status = _corpus.status_of(entry)
        if status != "pass":
            groups.setdefault((suite["id"], status, entry.get("issue"), entry["reason"]), []).append(entry["id"])
    if not groups:
        add("None.")
    else:
        add("| Suite | Status | Issue | Cases | Why |")
        add("|---|---|---|---|---|")
        for (suite_id, status, issue, reason), ids in groups.items():
            shown = ", ".join(f"`{i}`" for i in ids[:3]) + (f" and {len(ids) - 3} more" if len(ids) > 3 else "")
            add(f"| `{suite_id}` | `{status}` | {issue_link(issue)} | {shown} | {cell(reason)} |")
    add("")
    add("## Unsupported constructs")
    add("")
    add("The constructs the [conformance matrix](CONFORMANCE.md) marks unsupported or partial, and whether "
        "the corpus has a case that shows it. A case marked `gap` is a schema and data the source says "
        "are valid (or invalid) that the library gets wrong because the construct is not enforced.")
    add("")
    add("| Construct | Matrix status | Corpus cases | Showing the gap |")
    add("|---|---|--:|--:|")
    covering = {}
    for suite, entry in _corpus.iter_cases(suites):
        for row in entry.get("constructs", []):
            covering.setdefault(row, []).append(entry)
    for row_id, row in matrix_rows.items():
        if row["status"] not in ("unsupported", "partial"):
            continue
        cases = covering.get(row_id, [])
        gaps = [c for c in cases if _corpus.status_of(c) == "gap"]
        add(f"| {cell(row['construct'])} | {row['status']} | {len(cases) or 'none'} | {len(gaps) or ''} |")
    add("")
    add("## Layout")
    add("")
    add("```")
    add("tests/corpus/")
    add("  suites/<suite>.json    the cases of one suite, with its sources")
    add("  schemas/               the CDDL files the cases name (published text, kept unchanged)")
    add("tests/_corpus.py         loads and runs the corpus")
    add("tests/test_corpus.py     checks the format and runs every case")
    add("scripts/build_corpus.py  rebuilds the suites from clones of the upstream repositories")
    add("scripts/render_corpus.py writes this page")
    add("```")
    add("")
    add("A suite names its `sources` (name, URL, commit, licence), its `schema` (one file or a list that "
        "is joined), its `modules` (name to file, for `;# import`) and `provenance`. A case has:")
    add("")
    add("| Field | Meaning |")
    add("|---|---|")
    for field, text in (
            ("`id`", "unique name"),
            ("`hex`", "the CBOR, in hexadecimal (absent for a `schema-error` case)"),
            ("`edn`", "the published diagnostic notation `hex` was converted from, when there was one"),
            ("`expect`", "what the source says: `valid`, `invalid`, or `schema-error` (the schema itself is refused)"),
            ("`status`", "`pass` (the default) or why the library differs"),
            ("`issue`, `reason`", "the issue a `gap` waits on; the reason for a `gap`, `divergence` or `source-defect`"),
            ("`constructs`", "ids of the rows of the conformance matrix the case exercises"),
            ("`source`", "where in the source the case comes from, or what was changed to derive it"),
            ("`provenance`", "see above; on the suite when every case shares it"),
            ("`schema`, `root`, `modules`", "override the suite's; `root` defaults to the first rule"),
            ("`encoding`", "`sequence` for a CBOR sequence (RFC 8742): the items are checked as the array `root` describes"),
            ("`deterministic`", "check with `require_deterministic` (RFC 8949 §4.2.1)"),
            ("`note`", "anything else worth knowing")):
        add(f"| {field} | {text} |")
    add("")
    add("## Adding or updating cases")
    add("")
    add("- A case from a new source: add a builder to `scripts/build_corpus.py` (clone the source, record its "
        "commit and licence, take the schema and data from it) and run `python scripts/build_corpus.py "
        "--sources DIR`. The script stops on a case the library disagrees with that nothing explains.")
    add("- A library fix that makes a `gap` or `divergence` case agree: the test fails on it. Remove the "
        "explanation in `scripts/build_corpus.py`, rebuild, and run `python scripts/render_corpus.py`.")
    add("- Run the corpus: `python -m pytest tests/test_corpus.py`.")
    add("")
    return "\n".join(out)


def main(argv=None):
    argv = sys.argv[1:] if argv is None else argv
    text = render(_corpus.load_suites(), _corpus.matrix_rows())
    if "--check" in argv:
        if OUTPUT.read_text(encoding="utf-8") != text:
            print(f"{OUTPUT} is out of date: run python scripts/render_corpus.py", file=sys.stderr)
            return 1
        return 0
    with open(OUTPUT, "w", encoding="utf-8", newline="\n") as handle:
        handle.write(text)
    print(f"wrote {OUTPUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
