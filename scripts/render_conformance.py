#!/usr/bin/env python3
"""Write docs/CONFORMANCE.md from docs/conformance.json (#86).

Usage: ``python scripts/render_conformance.py`` (``--check`` only compares).
tests/test_conformance.py fails when the document and the data disagree.
"""

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DATA = ROOT / "docs" / "conformance.json"
OUTPUT = ROOT / "docs" / "CONFORMANCE.md"
REPO = "https://github.com/sahebbiswas/cddl_verifier"

MARKS = {"supported": "✅", "partial": "🟡", "unsupported": "❌", "n/a": "–", "out-of-scope": "⛔"}
AREAS = [
    ("syntax", "CDDL syntax and semantics",
     "Constructs of the RFC 8610 grammar (as updated by RFC 9682), the modules draft, and the "
     "schema checks done before any data is seen."),
    ("control", "Control operators",
     "Every operator the resolver knows (RFC 8610, RFC 9165, RFC 9741). An operator the "
     "validator does not enforce still parses and resolves, and accepts any value."),
    ("prelude", "Prelude types (RFC 8610 Appendix D)", "One row per group of related names."),
    ("cbor", "CBOR data model (RFC 8949)",
     "What the decoder, encoder, validator, EDN output and typed JSON bridge do with each kind of item."),
]
HEAD = {
    "syntax": ("Parser", "AST", "Resolver", "Validator", "EDN"),
    "control": ("Parser", "AST", "Resolver", "Validator", "EDN"),
    "prelude": ("Parser", "AST", "Resolver", "Validator", "EDN"),
    "cbor": ("Decoder", "Encoder", "Validator", "EDN", "JSON"),
}


def cell(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " ")


def issues(numbers) -> str:
    return ", ".join(f"[#{n}]({REPO}/issues/{n})" for n in numbers)


def render(matrix: dict) -> str:
    rows = matrix["rows"]
    out = [
        "# Conformance matrix",
        "",
        "<!-- Generated by scripts/render_conformance.py from docs/conformance.json: do not edit. -->",
        "",
        "What each CDDL construct, control operator and CBOR item does in each layer of the library, "
        "and how that is tested. Every claim is checked by `tests/test_conformance.py`, which runs the "
        "examples in [docs/conformance.json](conformance.json) against the code, so this page cannot "
        "describe behaviour the code does not have. See [CDDL_SUPPORT.md](CDDL_SUPPORT.md) for how "
        "each supported construct behaves.",
        "",
        "| Mark | Meaning |",
        "|------|---------|",
        "| ✅ | supported: accepted, resolved and enforced; examples and tests cover it |",
        "| 🟡 | partial: works for some uses; the notes say which |",
        "| ❌ | unsupported: the layer does not do it (an operator that is parsed but not enforced accepts any value) |",
        "| – | not applicable to this layer |",
        "| ⛔ | out of scope |",
        "",
        "Layers: the **parser** reads the syntax into the typed **AST**; the **resolver** checks names, kinds "
        "and controls and reports `SchemaError`s; the **validator** checks data; **EDN** is the annotated "
        "diagnostic output; **JSON** is the typed JSON bridge.",
        "",
        "## Summary",
        "",
        "| Area | ✅ supported | 🟡 partial | ❌ unsupported | Total |",
        "|------|-------------:|-----------:|---------------:|------:|",
    ]
    for key, title, _ in AREAS:
        area = [r for r in rows if r["area"] == key]
        counts = [sum(r["status"] == s for r in area) for s in ("supported", "partial", "unsupported")]
        out.append(f"| {title} | {counts[0]} | {counts[1]} | {counts[2]} | {len(area)} |")
    for key, title, blurb in AREAS:
        out += ["", f"## {title}", "", blurb, ""]
        head = HEAD[key]
        out.append("| Construct | Spec | Status | " + " | ".join(head) + " | Notes | Tests |")
        out.append("|" + "|".join(["---"] * 3 + [":-:"] * len(head) + ["---", "---"]) + "|")
        for r in (r for r in rows if r["area"] == key):
            layers = " | ".join(MARKS[state] for state in r["layers"].values())
            notes = cell(r["notes"])
            if r["issues"]:
                notes = (notes + " " if notes else "") + issues(r["issues"])
            tests = ", ".join(f"`{Path(t).name}`" for t in r["tests"])
            out.append(f"| {cell(r['construct'])} | {cell(r['spec'])} | {MARKS[r['status']]} | "
                       f"{layers} | {notes} | {tests} |")
    out += ["", "## Out of scope", "", "| Item | Why |", "|------|-----|"]
    for item in matrix.get("out_of_scope", ()):
        out.append(f"| {cell(item['construct'])} | {cell(item['reason'])} |")
    out += [
        "",
        "## Updating",
        "",
        "Edit [conformance.json](conformance.json), then run `python scripts/render_conformance.py` to rewrite "
        "this page. A change that adds a construct, enforces a control, or fixes a gap needs its row in the "
        "same pull request:",
        "",
        "- `status` is `supported`, `partial`, `unsupported` or `out-of-scope`; `layers` gives each layer "
        "`supported`, `partial`, `unsupported` or `n/a`. A row that is not supported names the issue that tracks it.",
        "- `tests` lists the test files that cover the row (they must exist).",
        "- `probes` are run by the test. Each has a `schema` (and optionally a `root` or `modules`) and lists of "
        "data: `valid` must be accepted, `invalid` rejected. `accepted_but_invalid` and `rejected_but_valid` "
        "record a known gap, and the test fails when the code stops behaving that way, so a fix cannot "
        "leave the row behind. Data is JSON, with `{\"$bytes\": hex}`, `{\"$tag\": n, \"$value\": v}`, "
        "`{\"$map\": [[k, v], ...]}`, `{\"$float\": \"nan\"}`, `{\"$undefined\": true}` and "
        "`{\"$simple\": n}` for what JSON cannot write.",
        "- `schema_errors` are schemas that must raise `SchemaError`.",
        "- `cbor` items (CBOR rows) give the hex input, whether it decodes, and whether it round-trips through the "
        "encoder, the canonical encoder and typed JSON.",
        "- New controls and prelude names need a row (`covers` lists the prelude names a row stands for): the "
        "test compares them with what the resolver and prelude define.",
        "",
    ]
    return "\n".join(out)


def main(argv=None) -> int:
    args = list(sys.argv[1:] if argv is None else argv)
    text = render(json.loads(DATA.read_text(encoding="utf-8")))
    if "--check" in args:
        if OUTPUT.read_text(encoding="utf-8") != text:
            print(f"{OUTPUT} is out of date", file=sys.stderr)
            return 1
        return 0
    OUTPUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUTPUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
